// =============================================================================
// tools/build-vsop87.mjs — Dev-only: build js/data/vsop87a.js from the VSOP87A series
// (Bretagnon & Francou 1988: heliocentric rectangular coordinates, dynamical ecliptic and
// equinox J2000, AU; time in Julian millennia TDB from J2000).
//   node tools/build-vsop87.mjs [--dir <folder with VSOP87A.*>] [--eps <AU fraction>] [--dry]
// The files are downloaded from IMCCE into .cache/vsop87 if they are not there.
// Truncation: a term A·t^k·cos(B + C·t) is kept when A·TMAX^k ≥ eps·a, with a the planet's
// semi-major axis and TMAX = 0.25 millennia (the simulator covers 1800–2050, |t| ≤ 0.2).
// The script prints the worst difference between the truncated and the full series so the
// truncation error is known; tests/accuracy.test.mjs then checks the result against Horizons.
// =============================================================================
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, def) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : def; };
const dir = path.resolve(arg('--dir', path.join(root, '.cache', 'vsop87')));
const EPS = +arg('--eps', '1e-7');
const TMAX = 0.25;
const SRC = 'https://ftp.imcce.fr/pub/ephem/planets/vsop87/';
const BODIES = { mercury: ['mer', 0.387], venus: ['ven', 0.723], emb: ['emb', 1.0], mars: ['mar', 1.524],
  jupiter: ['jup', 5.203], saturn: ['sat', 9.537], uranus: ['ura', 19.19], neptune: ['nep', 30.07] };

mkdirSync(dir, { recursive: true });
async function load(ext) {
  const f = path.join(dir, `VSOP87A.${ext}`);
  if (!existsSync(f)) {
    const r = await fetch(SRC + `VSOP87A.${ext}`);
    if (!r.ok) throw new Error(`download VSOP87A.${ext}: HTTP ${r.status}`);
    writeFileSync(f, await r.text());
  }
  // series[v][k] = [[A, B, C], ...]   v = 0..2 (X, Y, Z), k = power of t
  const series = [[], [], []];
  let cur = null;
  for (const line of readFileSync(f, 'utf8').split(/\r?\n/)) {
    const h = /VARIABLE (\d) \(XYZ\)\s+\*T\*\*(\d)\s+(\d+) TERMS/.exec(line);
    if (h) { cur = series[+h[1] - 1][+h[2]] = []; continue; }
    if (!line.trim()) continue;
    const n = line.trim().split(/\s+/), m = n.length;
    cur.push([+n[m - 3], +n[m - 2], +n[m - 1]]);
  }
  return series;
}
const evalSeries = (s, t) => s.map((pw) => { let v = 0, tk = 1; for (const terms of pw) { let q = 0; for (const [A, B, C] of terms) q += A * Math.cos(B + C * t); v += q * tk; tk *= t; } return v; });
const num = (x, d) => { let s = x.toFixed(d).replace(/0+$/, '').replace(/\.$/, ''); if (s === '-0') s = '0'; return s.replace(/^0\./, '.').replace(/^-0\./, '-.'); };

let js = `// =============================================================================
// data/vsop87a.js — GENERATED by tools/build-vsop87.mjs; do not edit by hand.
// VSOP87A (P. Bretagnon & G. Francou, 1988, A&A 202, 309): heliocentric rectangular coordinates
// of Mercury–Neptune and the Earth–Moon barycentre, dynamical ecliptic and equinox J2000, in AU.
// Truncated for 1800–2050: terms smaller than ${EPS} of the semi-major axis are dropped.
// VSOP87A[body][axis][power] = flat [A, B, C, A, B, C, ...];  coordinate = Σ_k t^k Σ A·cos(B + C·t),
// t = Julian millennia (TDB) from J2000.
// =============================================================================
export const VSOP87A = {\n`;
let total = 0;
for (const [key, [ext, a]] of Object.entries(BODIES)) {
  const full = await load(ext);
  const cut = full.map((pw) => pw.map((terms, k) => terms.filter(([A]) => Math.abs(A) * TMAX ** k >= EPS * a)));
  while (cut.some((pw) => pw.length && !pw[pw.length - 1].length)) cut.forEach((pw) => { if (pw.length && !pw[pw.length - 1].length) pw.pop(); });
  let worst = 0;
  for (let i = 0; i <= 400; i++) {
    const t = -0.2 + 0.4 * (i / 400) + 1e-4, f = evalSeries(full, t), c = evalSeries(cut, t);
    worst = Math.max(worst, Math.hypot(f[0] - c[0], f[1] - c[1], f[2] - c[2]));
  }
  const n = cut.flat(2).length, nf = full.flat(2).length;
  total += n;
  console.log(`${key.padEnd(8)} ${String(n).padStart(5)} of ${String(nf).padStart(5)} terms; truncation ≤ ${(worst * 149597870.7).toFixed(0)} km = ${(worst / a * 206264.8).toFixed(3)}″ from the Sun`);
  js += `  ${key}: [\n` + cut.map((pw) => '    [' + pw.map((terms) => '[' + terms.map(([A, B, C]) => `${num(A, 11)},${num(B, 9)},${num(C, 7)}`).join(',') + ']').join(',\n     ') + ']').join(',\n') + '],\n';
}
js += '};\n';
console.log(`total ${total} terms, ${(js.length / 1024).toFixed(0)} kB`);
if (!process.argv.includes('--dry')) { writeFileSync(path.join(root, 'js', 'data', 'vsop87a.js'), js); console.log('wrote js/data/vsop87a.js'); }
