// =============================================================================
// tools/build-pluto.mjs — Dev-only: build js/data/plutoTrack.js from JPL Horizons.
//   node tools/build-pluto.mjs [--step <days>] [--dry]
// VSOP87 has no Pluto, so its position comes from a table: heliocentric (Sun centre) ecliptic
// J2000 state vectors of the Pluto–Charon barycentre (Horizons body 9, DE441), every STEP days
// from 1799 to 2051, interpolated with cubic Hermite polynomials in ephemeris.js.
// The script downloads at STEP/2 and uses the in-between samples to measure the interpolation error.
// =============================================================================
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, def) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : def; };
const STEP = +arg('--step', '200');
const JD0 = 2378132.5;                                  // 1799-01-01 TDB
const N = Math.ceil((2470536.5 - JD0) / STEP) + 1;       // through 2051-12-31
const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchStates(jds) {
  const out = [];
  for (let i = 0; i < jds.length; i += 40) {
    const p = new URLSearchParams({ format: 'json', COMMAND: "'9'", OBJ_DATA: "'NO'", MAKE_EPHEM: "'YES'",
      EPHEM_TYPE: "'VECTORS'", CENTER: "'500@10'", REF_PLANE: "'ECLIPTIC'", REF_SYSTEM: "'J2000'",
      VEC_TABLE: "'2'", OUT_UNITS: "'KM-D'", CSV_FORMAT: "'YES'", VEC_LABELS: "'NO'", TLIST: `'${jds.slice(i, i + 40).join("','")}'` });
    const j = await (await fetch(`${API}?${p}`)).json();
    if (!j.result || !j.result.includes('$$SOE')) throw new Error(`Horizons: ${String(j.result || j.error).slice(0, 400)}`);
    for (const l of j.result.split('$$SOE')[1].split('$$EOE')[0].trim().split('\n')) {
      const c = l.split(',').map((s) => s.trim());
      out.push(c.slice(2, 8).map(Number));
    }
    await sleep(400);
    process.stdout.write(`\r${out.length} / ${jds.length}`);
  }
  process.stdout.write('\n');
  return out;
}

const half = [];
for (let i = 0; i < 2 * N - 1; i++) half.push(JD0 + (i * STEP) / 2);
const st = await fetchStates(half);
const nodes = st.filter((_, i) => i % 2 === 0);

// Interpolation error at the midpoints (s = 0.5: h00 = h01 = 0.5, h10 = 0.125, h11 = −0.125).
let worst = 0;
for (let i = 0; i < N - 1; i++) {
  const a = nodes[i], b = nodes[i + 1], m = st[2 * i + 1];
  const e = [0, 1, 2].map((k) => 0.5 * a[k] + 0.125 * STEP * a[3 + k] + 0.5 * b[k] - 0.125 * STEP * b[3 + k] - m[k]);
  worst = Math.max(worst, Math.hypot(...e));
}
console.log(`${N} samples every ${STEP} d; interpolation error at midpoints ≤ ${worst.toFixed(1)} km (${(worst / 5e9 * 206264.8).toFixed(4)}″ at 33 AU)`);

const js = `// =============================================================================
// data/plutoTrack.js — GENERATED by tools/build-pluto.mjs; do not edit by hand.
// Pluto–Charon barycentre, heliocentric (Sun centre) ecliptic J2000, from JPL Horizons (DE441).
// data = flat [x, y, z (km), vx, vy, vz (km/day)] every \`step\` days from \`jd0\` (TDB),
// 1799–2051. Cubic Hermite interpolation error ≤ ${Math.ceil(worst)} km.
// =============================================================================
export const PLUTO_TRACK = {
  jd0: ${JD0}, step: ${STEP},
  data: [
${nodes.map((s) => '    ' + s.map((v, k) => (k < 3 ? Math.round(v) : +v.toFixed(3))).join(',')).join(',\n')},
  ],
};
`;
console.log(`${(js.length / 1024).toFixed(0)} kB`);
if (!process.argv.includes('--dry')) { writeFileSync(path.join(root, 'js', 'data', 'plutoTrack.js'), js); console.log('wrote js/data/plutoTrack.js'); }
